"""Page profiling for `scripts/perf/api_latency.py`: the memory guard, the page / operation
selection and `--profile` (one uncached call per operation, in process, under cProfile).

Bucket method (docs/perf/api-latency-uncached-run.md, "run it page by page"): cProfile gives per
function its own time (`tottime`) and, per caller edge, the time spent below that edge. A function
named by a bucket rule (a filesystem call, `runs.py from_json`, anything in pyarrow, pandas, the
GraphQL / JSON encoders) puts its own time in that bucket; every other function splits its own time
over its callers' buckets in proportion to the edge time, recursively, and code nobody named is
"other". Each second of own time lands in exactly one bucket, so the buckets sum to the profile's
total: nothing is counted twice (summing cumulative times of nested entry points would). Wall is the
profiled call's wall time (cProfile overhead inflates pure-Python time, so read the shares, not the
absolute split). Nothing here touches a store: `run_profile` is only called with a clone's URL.
"""

from __future__ import annotations

import asyncio
import cProfile
import itertools
import os
import pstats
import re
import shutil
import signal
import subprocess
import sys
import time
from collections import defaultdict
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

MIN_FREE_SWAP_MB = 500.0
MIN_FREE_DISK_GB = 8.0
EXIT_LOW_SWAP = 3
SNAPSHOT_S = 60.0
STABLE_POINTS = 0.05
PRIME = "query SessionDate { session { date } }"
TOP_N = 12
HEADER = (
    '# Page profiles\n\nGenerated by `make api-latency ARGS="--profile --page ROUTE --data-url '
    '..."` (`scripts/perf/page_profile.py`); do not edit. One section per page, replaced when the '
    "page is profiled again. Method and caveats: `docs/perf/api-latency-uncached-run.md`.\n"
)
SWAP_FREE = re.compile(r"free\s*=\s*([\d.]+)\s*([MG])", re.I)


class SwapLowError(Exception):
    """Free swap fell below the floor: the run stops before it pushes the machine over."""


class SelectionError(Exception):
    """A --page / --ops value names nothing the tool can measure."""


# ---- memory guard ---------------------------------------------------------------------------


def parse_swap_free_mb(text: str) -> float | None:
    """Free swap in MB from `sysctl vm.swapusage` output; None when the text has no `free =`."""
    found = SWAP_FREE.search(text)
    if not found:
        return None
    return float(found.group(1)) * (1024.0 if found.group(2).upper() == "G" else 1.0)


def read_swap_free_mb() -> float | None:
    """Free swap now (macOS `sysctl vm.swapusage`); None where it cannot be read."""
    try:
        done = subprocess.run(
            ["sysctl", "-n", "vm.swapusage"], capture_output=True, text=True, check=False
        )
    except OSError:
        return None
    return parse_swap_free_mb(done.stdout) if done.returncode == 0 else None


def swap_guard(
    min_free_mb: float = MIN_FREE_SWAP_MB,
    reader: Callable[[], float | None] = read_swap_free_mb,
    disk_path: Path | None = None,
    disk_free_gb: Callable[[Path], float] = lambda p: shutil.disk_usage(p).free / 1024**3,
    min_disk_gb: float = MIN_FREE_DISK_GB,
) -> None:
    """Raise SwapLowError when free swap is under ``min_free_mb``, or the disk holding
    ``disk_path`` (the clone) has under ``min_disk_gb`` free; an unreadable swap value passes."""
    free = reader()
    if free is not None and free < min_free_mb:
        raise SwapLowError(f"free swap {free:.0f} MB is below {min_free_mb:.0f} MB")
    if disk_path is not None:
        gb = disk_free_gb(disk_path)
        if gb < min_disk_gb:
            raise SwapLowError(
                f"free disk {gb:.1f} GB under {disk_path} is below {min_disk_gb:.0f} GB"
            )


# ---- selection ------------------------------------------------------------------------------


def select_operations(
    ops: dict[str, dict],
    by_page: dict[str, list[str]],
    routes: list[str],
    names: list[str],
    static_by_route: dict[str, list[str]],
) -> dict[str, dict]:
    """The operations of the given routes (the capture's, else the static on-load map's) plus the
    named ones, each once, in page order. A route or name nothing knows is an error."""
    chosen: list[str] = []
    for route in routes:
        listed = by_page.get(route)
        if listed is None:
            listed = static_by_route.get(route)
        if listed is None:
            raise SelectionError(f"--page {route}: no such route (known: {sorted(by_page)})")
        chosen += listed
    chosen += names
    out: dict[str, dict] = {}
    for name in chosen:
        if name not in ops:
            raise SelectionError(f"operation {name}: no captured document or variables for it")
        out.setdefault(name, ops[name])
    return out


# ---- bucket attribution ---------------------------------------------------------------------

BUCKETS = (
    "filesystem walks",
    "run-record decode",
    "Parquet / Arrow",
    "pandas / numpy",
    "GraphQL / JSON serialisation",
    "other",
)
FS = re.compile(
    r"posix\.(stat|lstat|fstat|listdir|scandir|access)|pathlib.*:(exists|is_dir|is_file|iterdir)"
    r"|genericpath.*:(exists|isdir|isfile)"
)
SERIALISE = re.compile(r"site-packages/graphql/|/strawberry/|json/encoder\.py|gzip\.py|orjson")
OPEN = ("io.open", "posix.open", "builtins.open", "function open>")
Key = tuple[str, int, str]


def own_bucket(key: Key) -> str | None:
    """The bucket a function names by itself, or None (it then follows its callers)."""
    file, _, name = key
    label = f"{file}:{name}"
    if FS.search(label):
        return BUCKETS[0]
    if (file.endswith("storage/runs.py") and name == "from_json") or (
        file.endswith("storage/backends/local.py") and name in ("_record", "find")
    ):
        return BUCKETS[1]
    if "pyarrow" in label:
        return BUCKETS[2]
    if "/pandas/" in file or "/numpy/" in file or "numpy" in name:
        return BUCKETS[3]
    if SERIALISE.search(label):
        return BUCKETS[4]
    return None


def attribute(stats: dict[Key, tuple]) -> dict[str, float]:
    """Seconds per bucket from a pstats table ({key: (cc, nc, tt, ct, callers)}); sums to the
    profile's total own time (the method is in the module docstring)."""
    memo: dict[Key, dict[str, float]] = {}

    def share(key: Key, visiting: frozenset[Key]) -> dict[str, float]:
        if key in memo:
            return memo[key]
        own = own_bucket(key)
        if own is not None:
            out = {own: 1.0}
        elif key in visiting:
            return {"other": 1.0}
        else:
            callers = {c: e[3] for c, e in stats[key][4].items() if c in stats}
            total = sum(callers.values())
            out = defaultdict(float)
            if total <= 0:
                out["other"] = 1.0
            for c, w in callers.items():
                if total > 0:
                    for b, f in share(c, visiting | {key}).items():
                        out[b] += f * w / total
        memo[key] = dict(out)
        return memo[key]

    buckets: dict[str, float] = defaultdict(float)
    for key, row in stats.items():
        for b, f in share(key, frozenset()).items():
            buckets[b] += row[2] * f
    return dict(buckets)


def call_counts(stats: dict[Key, tuple]) -> dict[str, int]:
    """stat calls (posix stat / lstat) and files opened, from the profile's call counts."""
    return {
        "stat calls": sum(r[1] for k, r in stats.items() if re.search(r"posix\.l?stat", k[2])),
        "files opened": sum(r[1] for k, r in stats.items() if any(o in k[2] for o in OPEN)),
    }


def short(key: Key) -> str:
    file, line, name = key
    for marker in ("site-packages/", "/src/", "/apps/", "/libs/"):
        if marker in file:
            file = file.split(marker, 1)[1]
            break
    return f"{file}:{line}({name})"


def saw_nothing(stats: dict[Key, tuple]) -> bool:
    """A profile with no stat calls and no algotrade function: the work ran in a thread the
    profiler did not watch."""
    return call_counts(stats)["stat calls"] == 0 and not any("algotrade" in k[0] for k in stats)


def top_functions(stats: dict[Key, tuple], n: int = TOP_N) -> list[dict]:
    """The ``n`` functions of algotrade and pyarrow with the largest cumulative time."""
    mine = [(k, r) for k, r in stats.items() if "algotrade" in k[0] or "pyarrow" in k[0]]
    mine.sort(key=lambda kr: -kr[1][3])
    return [{"function": short(k), "cumulative_s": r[3], "calls": r[1]} for k, r in mine[:n]]


# ---- the generated page file ----------------------------------------------------------------


def shares(snap: dict) -> dict[str, float]:
    total = sum(snap["buckets"].values()) or 1.0
    return {b: snap["buckets"].get(b, 0.0) / total for b in BUCKETS}


def stability(snaps: list[dict]) -> str:
    """The STABILITY line: the last 3 snapshots' bucket shares each moved under 5 points."""
    if len(snaps) < 3:
        return "STABILITY: too few snapshots to judge (treat as indicative)"
    last = [shares(x) for x in snaps[-3:]]
    moved = max(abs(b[k] - a[k]) for a, b in itertools.pairwise(last) for k in BUCKETS)
    if moved < STABLE_POINTS:
        return "STABILITY: shares stable"
    return "STABILITY: shares still moving (treat as indicative)"


def trend_table(snaps: list[dict]) -> list[str]:
    """Per snapshot: elapsed, share per bucket, stat calls and files opened so far and per s."""
    lines = [
        "| elapsed s | "
        + " | ".join(BUCKETS)
        + " | stat calls | files opened | stat/s | files/s |",
        "|---:|" + "---:|" * (len(BUCKETS) + 4),
    ]
    for x in snaps:
        sh, c, t = shares(x), x["counts"], x["t"] or 1.0
        lines.append(
            f"| {x['t']:.0f} | "
            + " | ".join(f"{sh[b]:.0%}" for b in BUCKETS)
            + f" | {c['stat calls']:,} | {c['files opened']:,} | {c['stat calls'] / t:,.0f} | "
            f"{c['files opened'] / t:,.0f} |"
        )
    return lines


def partial_lines(part: dict) -> list[str]:
    return [
        "Bucket SHARES are meaningful; absolute seconds are lower bounds (the call was cut). "
        "Rows and bytes are not known for a cut call.",
        "",
        *trend_table(part["snapshots"]),
        "",
        stability(part["snapshots"]),
        "",
    ]


def render_page(route: str, rows: list[dict]) -> str:
    lines = [f"## `{route}`", ""]
    for r in rows:
        status = f" **FAILED: {r['error']}** (timings are of an error)" if r["error"] else ""
        status += f" **{r['note']}**" if r.get("note") else ""
        part = r.get("partial")
        if part:
            status += (
                f" **PARTIAL: profiled for {part['elapsed']:.0f} s, the call had not finished "
                f"({part['reason']})**"
            )
        status += (
            " **PROFILE SAW NOTHING (thread issue)**: no stat calls and no algotrade function; "
            "do not read the buckets"
            if r.get("saw_nothing")
            else ""
        )
        total = sum(r["buckets"].values()) or 1.0
        lines += [
            f"### {r['op']}{status}",
            "",
            f"wall {r['wall_s']:.2f} s (profiled), {r['bytes']:,} bytes, {r['rows']} rows, "
            f"{r['counts']['stat calls']:,} stat calls, {r['counts']['files opened']:,} files "
            "opened.",
            "",
            "| bucket | seconds | share |",
            "|---|---:|---:|",
            *[
                f"| {b} | {s:.2f} | {s / total:.0%} |"
                for b, s in sorted(r["buckets"].items(), key=lambda kv: -kv[1])
            ],
            "",
            *(partial_lines(part) if part else []),
            f"| top {len(r['top'])} by cumulative (algotrade, pyarrow) | cumulative s | calls |",
            "|---|---:|---:|",
            *[
                f"| `{t['function']}` | {t['cumulative_s']:.2f} | {t['calls']:,} |"
                for t in r["top"]
            ],
            "",
        ]
    return "\n".join(lines)


def upsert_section(doc: str, route: str, section: str) -> str:
    """``doc`` with the ``## `route` `` section replaced by ``section`` (or appended)."""
    doc = doc or HEADER
    heading = f"## `{route}`"
    parts = re.split(r"(?m)^(?=## )", doc)
    kept = [p for p in parts if not p.startswith(heading + "\n")]
    return "".join(kept).rstrip("\n") + "\n\n" + section.rstrip("\n") + "\n"


# ---- the in-process run ---------------------------------------------------------------------


def run_profile(
    ops: dict[str, dict],
    label: str,
    *,
    patch: str,
    data_url: str,
    config_dir: Path,
    out: Path,
    problem: Callable[[int, bytes], str | None],
    rows_of: Callable[[Any], int],
    min_free_mb: float = MIN_FREE_SWAP_MB,
    disk_path: Path | None = None,
    notes_of: Callable[[int, bytes], str | None] = lambda *_: None,
    limit_s: float | None = None,
    snapshot_s: float = SNAPSHOT_S,
) -> int:
    """One uncached call per operation under cProfile, in this process (the caller starts one
    process per page): the same patches as the uncached mode, the warmer off, a TestClient. The
    page's section in ``out`` is rewritten after every operation, so a stop keeps what ran."""
    if not data_url:
        raise ValueError("--profile needs a clone's data URL")
    os.environ.update(
        ALGOTRADE_AUTH="off",
        ALGOTRADE_LLM="off",
        ALGOTRADE_IBKR_PORT="1",
        ALGOTRADE_DATA_URL=data_url,
        ALGOTRADE_CONFIG_DIR=str(config_dir),
    )
    argv, sys.argv = sys.argv, ["x", "0", "2"]
    try:
        exec(compile(patch, "<perf-patch>", "exec"), {"__name__": "perf_patch"})
    finally:
        sys.argv = argv
    return _profile_all(
        ops, label, out, problem, rows_of, min_free_mb, disk_path, notes_of, limit_s, snapshot_s
    )


async def _inline_sync(func: Callable[..., Any], *args: Any, **_: Any) -> Any:
    return func(*args)


async def _inline_thread(func: Callable[..., Any], *args: Any, **kwargs: Any) -> Any:
    return func(*args, **kwargs)


class Cut(KeyboardInterrupt):
    """A private stop raised in the profiling thread: the time limit, or SIGTERM / SIGHUP / SIGINT.
    A KeyboardInterrupt, so asyncio's task step lets it out of the loop and nothing in the app's
    ``except Exception`` can swallow it."""

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


@dataclass
class Profiled:
    """What ``run_profiled`` saw: the call's value, the profile, the snapshots, why it was cut."""

    value: Any = None
    stats: dict = field(default_factory=dict)
    snapshots: list[dict] = field(default_factory=list)
    cut: str | None = None
    elapsed: float = 0.0


def snapshot_of(stats: dict[Key, tuple], elapsed: float) -> dict:
    """The bucket seconds and call counters of a profile so far."""
    return {"t": elapsed, "buckets": attribute(stats), "counts": call_counts(stats)}


def run_profiled(
    call: Callable[[], Any],
    *,
    limit_s: float | None,
    snapshot_s: float = SNAPSHOT_S,
    clock: Callable[[], float] = time.perf_counter,
    on_cut: Callable[[], None] = lambda: None,
) -> Profiled:
    """``call()`` under cProfile in this (the main) thread. A SIGALRM every ``snapshot_s`` disables
    the profiler, keeps a snapshot, and re-enables it; at ``limit_s`` it raises ``Cut`` inside the
    call instead, and a ``Cut`` from a signal handler (SIGTERM...) ends it the same way. A cut
    call still returns its profile (``cut`` says why); ``on_cut`` cleans up what it left running."""
    prof = cProfile.Profile()
    snaps: list[dict] = []
    t0 = clock()

    def tick(_signum: int, _frame: object) -> None:
        elapsed = clock() - t0
        prof.disable()
        snaps.append(snapshot_of(pstats.Stats(prof).stats, elapsed))  # type: ignore[attr-defined]
        if limit_s is not None and elapsed >= limit_s - 0.001:
            raise Cut("limit")
        signal.setitimer(
            signal.ITIMER_REAL,
            snapshot_s if limit_s is None else max(0.001, min(snapshot_s, limit_s - elapsed)),
        )
        prof.enable()

    old = signal.signal(signal.SIGALRM, tick)
    result = Profiled()
    first = snapshot_s if limit_s is None else min(snapshot_s, limit_s)
    signal.setitimer(signal.ITIMER_REAL, first)
    prof.enable()
    try:
        result.value = call()
    except Cut as err:
        result.cut = err.reason
    finally:
        prof.disable()
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old)
    result.elapsed = clock() - t0
    try:
        result.stats = pstats.Stats(prof).stats  # type: ignore[attr-defined]
    except TypeError:  # nothing was profiled (cut at once)
        result.stats = {}
    result.snapshots = snaps
    if result.cut:
        result.snapshots = [*snaps, snapshot_of(result.stats, result.elapsed)]
        on_cut()
    return result


def partial_row(name: str, res: Profiled) -> dict:
    """The row of a call that was cut: final buckets, top functions, the trend and the reason."""
    return {
        "op": name,
        "wall_s": res.elapsed,
        "bytes": 0,
        "rows": 0,
        "error": None,
        "note": None,
        "saw_nothing": saw_nothing(res.stats),
        "buckets": attribute(res.stats),
        "counts": call_counts(res.stats),
        "top": top_functions(res.stats),
        "partial": {"reason": res.cut, "elapsed": res.elapsed, "snapshots": res.snapshots},
    }


def _flush(out: Path, label: str, done: list[dict]) -> None:
    current = out.read_text() if out.exists() else ""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(upsert_section(current, label, render_page(label, done)))


def _on_signal(signum: int, _frame: object) -> None:
    raise Cut(signal.Signals(signum).name)


def _profile_all(
    ops: dict[str, dict],
    label: str,
    out: Path,
    problem: Callable[[int, bytes], str | None],
    rows_of: Callable[[Any], int],
    min_free_mb: float,
    disk_path: Path | None,
    notes_of: Callable[[int, bytes], str | None],
    limit_s: float | None,
    snapshot_s: float,
) -> int:
    """Everything on this thread (cProfile watches only the thread that enables it): the app is
    driven through an ASGI transport on an event loop run from here, and the read pool's
    ``to_thread`` calls (anyio's, asyncio's) run inline, so the resolvers, gzip and storage reads
    are in the profile. The page's section is rewritten after every operation, and when the run
    is cut (limit, SIGTERM, SIGHUP, Ctrl-C) with what the cut call had gathered."""
    import anyio.to_thread  # noqa: PLC0415
    import httpx2 as httpx  # noqa: PLC0415

    from algotrade_api.app import app  # noqa: PLC0415  (after the environment is set)

    anyio.to_thread.run_sync = _inline_sync  # type: ignore[assignment]
    asyncio.to_thread = _inline_thread  # type: ignore[assignment]
    done: list[dict] = []
    code = 0
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    olds = {s: signal.signal(s, _on_signal) for s in (signal.SIGTERM, signal.SIGHUP, signal.SIGINT)}
    client = httpx.AsyncClient(
        transport=httpx.ASGITransport(app=app), base_url="http://127.0.0.1:8000", timeout=None
    )
    lifespan = app.router.lifespan_context(app)
    try:
        loop.run_until_complete(lifespan.__aenter__())
        loop.run_until_complete(client.post("/graphql", json={"query": PRIME}))  # schema, handles
        for name, op in ops.items():
            try:
                swap_guard(min_free_mb, disk_path=disk_path)
            except SwapLowError as err:
                print(f"aborted before {name}: {err}", file=sys.stderr)
                code = EXIT_LOW_SWAP
                break
            body = {"query": op["query"], "variables": op["variables"]}
            res = run_profiled(
                lambda body=body: loop.run_until_complete(client.post("/graphql", json=body)),
                limit_s=limit_s,
                snapshot_s=snapshot_s,
                on_cut=lambda: _drain(loop),
            )
            if res.cut:
                done.append(partial_row(name, res))
                print(f"  {name}: CUT ({res.cut}) after {res.elapsed:.0f} s", flush=True)
                _flush(out, label, done)
                if res.cut != "limit":
                    code = EXIT_LOW_SWAP
                    break
                continue
            r = res.value
            stats = res.stats
            err_text = problem(r.status_code, r.content)
            rows = rows_of(r.json().get("data")) if r.status_code == 200 and not err_text else 0
            done.append(
                {
                    "op": name,
                    "wall_s": res.elapsed,
                    "bytes": len(r.content),
                    "rows": rows,
                    "error": err_text,
                    "note": notes_of(r.status_code, r.content),
                    "saw_nothing": saw_nothing(stats),
                    "buckets": attribute(stats),
                    "counts": call_counts(stats),
                    "top": top_functions(stats),
                }
            )
            flag = "  PROFILE SAW NOTHING" if done[-1]["saw_nothing"] else ""
            print(
                f"  {name}: {res.elapsed:.2f} s, {len(r.content):,} B, {rows} rows"
                + (f"  FAILED: {err_text}" if err_text else "")
                + (f"  {done[-1]['note']}" if done[-1]["note"] else "")
                + flag,
                flush=True,
            )
            _flush(out, label, done)
    except Cut as err:  # a signal between operations: what ran is already written
        print(f"cut ({err.reason}) between operations", file=sys.stderr)
        code = EXIT_LOW_SWAP
    finally:
        for sig, old in olds.items():
            signal.signal(sig, old)
        _close(loop, client, lifespan)
    return code


def _drain(loop: asyncio.AbstractEventLoop) -> None:
    """Cancel what a cut call left pending and let it unwind (best effort)."""
    pending = [t for t in asyncio.all_tasks(loop) if not t.done()]
    for t in pending:
        t.cancel()
    if pending:
        loop.run_until_complete(asyncio.gather(*pending, return_exceptions=True))


def _close(loop: asyncio.AbstractEventLoop, client: Any, lifespan: Any) -> None:
    """Close the client and the app's lifespan; a failure here never hides the results."""
    try:
        loop.run_until_complete(client.aclose())
        loop.run_until_complete(lifespan.__aexit__(None, None, None))
    except BaseException as err:
        print(f"closing the app failed: {err!r}", file=sys.stderr)
    finally:
        loop.close()
