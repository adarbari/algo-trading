"""Page profiling for `scripts/perf/api_latency.py`: the memory guard, the page / operation
selection and `--profile` (one uncached call per operation, in process, under cProfile).

Bucket method (docs/perf/api-latency-uncached-run.md, "run it page by page"): cProfile gives per
function its own time (`tottime`) and, per caller edge, the time spent below that edge. A function
named by a bucket rule (a filesystem call, `runs.py from_json`, anything in pyarrow, pandas, the
GraphQL / JSON encoders) puts its own time in that bucket; every other function splits its own time
over its callers' buckets in proportion to the edge time, recursively, and code nobody named is
"other". Each second of own time lands in exactly one bucket, so the buckets sum to the profile's
total: nothing is counted twice (summing cumulative times of nested entry points would). Wall is the
profiled call's wall time (cProfile overhead inflates pure-Python time, so read the shares, not the
absolute split). Nothing here touches a store: `run_profile` is only called with a clone's URL.
"""

