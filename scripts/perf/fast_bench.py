"""`make api-latency-fast`: the page-latency bar over every web view: a gate and a history.

The bar (benchmarks/perf_bar.toml, owner decisions 2026-10-22): a VIEW is judged on its CRITICAL
PATH (its slowest request, the empty-cache first request) under 1 s, and the SHELL requests every
screen asks for (Viewer, SessionDate, Regime, StatusStrip, EdgeDesk, GuideEntries) together under
1 s. A view whose critical-path operation is a named exception (reason, approval, date and a live
expiry) may exceed it.
Exits 1 when a non-exempt view or the shell is over; 2 when refused.

Method: ONE API process on a CLONE of the store (`--data-url` is required; the real store is
refused as in api_latency.py), start-up warmer off, `release_reads=false`, and a patched endpoint
that empties the ResponseCache and every loader ResultCache before EVERY timing. Each distinct
(operation, document, variables) is timed 5 times and averaged (3 for operations whose first
timing is over 10 s) while the 1-minute load is gated at `--load-max` (a wait for it ends after
60 s: the pass runs and is flagged noisy). A wall-clock budget (`--budget-s`, default 270 s) stops
starting passes the mean of the passes so far predicts would overrun it: at least 2 passes, at
most `--reps`; fewer than 3 is LOW-CONFIDENCE and is not recorded. A view's critical path is
its slowest operation's average, its sum the total of its operations' averages. The views come from
the committed capture `benchmarks/api_latency_views.captured.json` (generated by `make
api-latency-views-capture` on the clone, never hand-edited; `--views-file` points at another copy;
without it the static list is measured with a loud warning: it has no variables).

`--ratio-mode` (a busy machine): every time is divided by the shell's slowdown against the last
recorded run (the shell operations are untouched by the work being judged), never below 1.
`--record` appends the run to benchmarks/critical_path_history.jsonl (the only writer; refused for
a run with a noisy operation or an `--only` subset, unless `--record-noisy`); `--history` prints
the trend and measures nothing. `--only Op1,Op2` (or env BENCH_ONLY) times just those operations
(a re-measure of one fix); with `--out` every pass dumps `samples-partial.json`, so an aborted run
keeps what it timed. The guards stay at their defaults (free swap, free disk of the clone's
volume): `--min-free-swap-mb` and `--min-free-disk-gb` are parameters, never lowered by the tool.
Docs: docs/perf/page-latency-bar.md.
"""

