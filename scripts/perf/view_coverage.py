"""The coverage report of the views file: every operation the web can send against the views that
trigger it, `docs/perf/view-coverage.md`. Pure: takes the parsed views file, the operation names
of the source and the old per-route capture; no server, no store."""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import views as v
import web_page_ops as wpo
from views import captured_requests

REPO = Path(__file__).resolve().parents[2]
WEB_SRC = REPO / "apps/web/src"
PAGES_FILE = REPO / "benchmarks/api_latency_pages.json"
DOC_OUT = REPO / "docs/perf/view-coverage.md"


def coverage(doc: dict, all_ops: set[str], old_pages: dict[str, list[dict]] | None = None) -> dict:
    """The facts of the report.

    ``triggered``: operation -> {view id: requests}, from the crawler's capture; ``expected``:
    operation -> view ids the static walk puts it in (on load, uncertain or interaction);
    ``untriggered``: operations no captured view sent, with where the static walk says they
    should be; ``no_data``: captured views that sent no GraphQL request; ``uncaptured``: views
    the crawler has not visited; ``delta``: operations and views against the old capture."""
    views = doc.get("views", {})
    triggered: dict[str, dict[str, int]] = {}
    expected: dict[str, list[str]] = {}
    no_data: list[str] = []
    uncaptured: list[str] = []
    for vid, view in views.items():
        for op in (*view.get("ops", []), *view.get("interaction", [])):
            expected.setdefault(op, []).append(vid)
        if "captured" not in view:
            uncaptured.append(vid)
            continue
        reqs = captured_requests(view)
        if not reqs:
            no_data.append(vid)
        for req in reqs:
            if view.get("clicks") and req.get("trigger") == "load":
                continue  # the page load of a sub-view is its parent view's, not the click's
            n = req.get("count", 1)
            triggered.setdefault(req["op"], {}).setdefault(vid, 0)
            triggered[req["op"]][vid] += n
    old_ops = {
        c["op"] for calls in (old_pages or {}).values() for c in calls if c["kind"] == "graphql"
    }
    new_ops = set(triggered)
    return {
        "operations": len(all_ops),
        "views": len(views),
        "captured_views": len(views) - len(uncaptured),
        "triggered": triggered,
        "expected": expected,
        "untriggered": {op: sorted(expected.get(op, [])) for op in sorted(all_ops - new_ops)},
        "no_data": sorted(no_data),
        "uncaptured": sorted(uncaptured),
        "delta": {
            "old_routes": len(old_pages or {}),
            "old_ops": len(old_ops),
            "new_ops": len(new_ops),
            "added_ops": sorted(new_ops - old_ops),
            "not_in_source": sorted(new_ops - all_ops),
        },
    }


def render(doc: dict, report: dict, generated: str) -> str:
    """The markdown report."""
    d = report["delta"]
    lines = [
        "# View coverage: every GraphQL operation against the views that trigger it",
        "",
        f"Generated by `make api-latency-views` ({generated}); do not edit. The views are "
        "found statically (`scripts/perf/views.py`) and visited by the crawler "
        "(`scripts/perf/capture_views.py`, on a CLONE of the store); a view is a route, its "
        "search values and the clicks that reach it.",
        "",
        f"- **{report['operations']}** query operations in the web source, "
        f"**{report['views']}** views, **{report['captured_views']}** captured.",
        f"- Old per-route capture: {d['old_routes']} routes, {d['old_ops']} operations; "
        f"views capture: {d['new_ops']} operations ({len(d['added_ops'])} new).",
        "",
        "## Operations no captured view triggered",
        "",
    ]
    if not report["captured_views"]:
        lines.append("_No view captured yet: run the crawler._")
    elif report["untriggered"]:
        lines += ["| operation | where the static walk expects it |", "|---|---|"]
        for op, where in report["untriggered"].items():
            lines.append(
                f"| {op} | {', '.join(f'`{w}`' for w in where) or 'nowhere (dead code?)'} |"
            )
    else:
        lines.append("None: every operation is triggered by a view.")
    lines += ["", "## Views with no data call", ""]
    lines += [f"- `{v}`" for v in report["no_data"]] or ["None."]
    lines += ["", "## Views not captured yet", ""]
    lines += [f"- `{v}`" for v in report["uncaptured"]] or ["None."]
    lines += ["", "## Per view: operations and request counts", ""]
    for vid, view in doc.get("views", {}).items():
        cap = view.get("captured")
        lines.append(f"### `{vid}`")
        lines.append("")
        if not cap:
            ops = ", ".join(view.get("ops", [])) or "none expected"
            lines += [f"Not captured. Static: {ops}.", ""]
            continue
        note = f" ({cap['status']}: {cap['note']})" if cap.get("note") else f" ({cap['status']})"
        lines.append(f"Status{note}.")
        reqs = captured_requests(view)
        if reqs:
            lines += ["", "| operation | requests | trigger | bytes |", "|---|---|---|---|"]
            for r in sorted(reqs, key=lambda r: r["op"]):
                lines.append(
                    f"| {r['op']} | {r.get('count', 1)} | {r.get('trigger', 'load')} | "
                    f"{r.get('bytes', 0):,} |"
                )
        if view.get("uncertain"):
            lines += ["", f"Statically uncertain: {', '.join(view['uncertain'])}."]
        lines.append("")
    if d["added_ops"]:
        lines += ["## Operations the views capture adds to the route capture", ""]
        lines += [f"- {op}" for op in d["added_ops"]] + [""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    """Re-enumerate the views (keeping what the crawler captured), write the views file and the
    coverage doc. No store, no server: safe on a busy machine."""
    merged = v.merge_static(v.load_views(), v.enumerate_views(WEB_SRC))
    v.save_views(merged)
    doc = v.load_views()
    pages = json.loads(PAGES_FILE.read_text())["pages"] if PAGES_FILE.is_file() else {}
    report = coverage(doc, wpo.all_query_ops(WEB_SRC), pages)
    DOC_OUT.parent.mkdir(parents=True, exist_ok=True)
    DOC_OUT.write_text(render(doc, report, f"{datetime.now(UTC):%Y-%m-%d %H:%M UTC}"))
    print(f"{report['views']} views, {report['operations']} operations; written {DOC_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
