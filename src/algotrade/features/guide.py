"""Render the field guide pages from the site field guide
(``config/site/field_guide/<group>/*.toml``, ADR 0041 amended): the index
``docs/data/field-guide.md`` (how to read the guide, the themes with their field counts, the
situations that fool several thresholds) and the theme pages under
``docs/data/field-guide/<group>/`` (each field with how to read it, a table of the usual
criterion per intent, the caveats and the sources). ``<group>`` is the theme's group in the
Guide's ``sections.toml``; a theme longer than ``PAGE_LINES`` is split at an entry boundary into
``<theme>.md``, ``<theme>-2.md``, ... so a page stays under the file-length cap. ``make
features-doc`` writes them next to the catalogue; ``tests/architecture/test_features.py`` keeps
them up to date."""

import json
from collections.abc import Iterable

from algotrade.config.site.field_guide import FieldGuideEntry, FieldGuideSettings, GuideUse
from algotrade.config.site.guide.sections import GuideSections
from algotrade.core.model.errors import ConfigurationError

PATH = "docs/data/field-guide.md"
DIR = "docs/data/field-guide"
SOURCE = "config/site/field_guide/"
PAGE_LINES = 900  # a generated page stays under this (the file-length cap is 1000)
TITLE_LINES = 4  # a theme page's title, its note and the blank lines after them

HEADER = f"""# Field guide: how to read the catalogue's fields

Generated by `make features-doc` from `{SOURCE}` (a folder per theme group);
edit those, not this page.
The same guide is shown by the Builder with each field and sent to the text model that drafts
a screen from a sentence (ADR 0041), so a threshold a person reads here is the threshold the
model proposes.

Every field is read the same way: **how to read it** (what low and high mean, in the field's
unit: a decimal field takes 0.10 for 10%), **the criterion per intent** (what a trader wants,
and the rule-screen criterion that expresses it: the operator, the value, the mode and the
near-miss band of [rules.md](../screeners/rules.md); `hard` rejects a miss, `soft` keeps a
near miss as a WATCH or a risk, `score` only ranks), and **when the reading lies**: the
situations in which the number is right and the conclusion is wrong, each with the field
that exposes it. The fields are on one page per theme (below). The
[situations](#situations-that-fool-several-thresholds) at the end of this page are the
ones that distort many fields at once; a screen that ignores them finds the same false
positives whatever its thresholds. A null never passes a `hard` criterion (missing data never
passes); a field's own catalogue entry ([features.md](features.md)) says when it is null.
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _value(value: object) -> str:
    return json.dumps(value)


def criterion_text(use: GuideUse) -> str:
    """``op value`` as a person reads it (``is_null`` and ``not_null`` take no value)."""
    if use.op in ("is_null", "not_null"):
        return use.op
    return f"{use.op} {_value(use.value)}"


def _tolerance(use: GuideUse) -> str:
    if use.tolerance is None:
        return "-"
    text = (
        _value(use.tolerance)
        if not isinstance(use.tolerance, dict)
        else (f"{use.tolerance['relative']:g} x the threshold")
    )
    return f"{text}, {use.on_miss}" if use.on_miss else text


def _uses(uses: Iterable[GuideUse]) -> list[str]:
    rows = [
        "| Intent | Criterion | Mode | Near-miss band | How to combine it |",
        "|---|---|---|---|---|",
    ]
    for u in uses:
        cells = [u.intent, f"`{criterion_text(u)}`", u.mode, _tolerance(u), u.note or "-"]
        rows.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return rows


def _entry(e: FieldGuideEntry) -> list[str]:
    lines = [f"### `{e.name}`", "", f"**How to read it.** {e.reads}", ""]
    if e.uses:
        lines += ["**The criterion per intent**", "", *_uses(e.uses), ""]
    if e.caveats:
        lines += ["**When the reading lies**", "", *[f"- {c}" for c in e.caveats], ""]
    if e.sources:
        lines += ["Sources: " + "; ".join(e.sources), ""]
    return lines


def _anchor(text: str) -> str:
    return "".join(ch for ch in text.lower().replace(" ", "-") if ch.isalnum() or ch == "-")


def _themes(guide: FieldGuideSettings) -> dict[str, list[FieldGuideEntry]]:
    """The entries by theme, themes in first appearance order, file order within."""
    themes: dict[str, list[FieldGuideEntry]] = {}
    for e in guide.fields:
        themes.setdefault(e.theme, []).append(e)
    return themes


def theme_path(group: str, theme: str, part: int = 1) -> str:
    """A theme's page: ``docs/data/field-guide/<group>/<slug>.md`` (part 1) or ``<slug>-<n>.md``."""
    suffix = "" if part == 1 else f"-{part}"
    return f"{DIR}/{group}/{_anchor(theme)}{suffix}.md"


def _groups(guide: FieldGuideSettings, sections: GuideSections) -> dict[str, str]:
    """The group id of every theme of the guide; a theme in no group is an error."""
    group_of = {t: g.id for g in sections.theme_groups for t in g.themes}
    missing = sorted({e.theme for e in guide.fields} - set(group_of))
    if missing:
        raise ConfigurationError(
            f"field guide themes in no theme group of config/site/guide/sections.toml: {missing}"
        )
    return group_of


def _parts(entries: Iterable[FieldGuideEntry]) -> list[list[FieldGuideEntry]]:
    """The entries cut into pages of at most ``PAGE_LINES`` lines, at entry boundaries."""
    parts: list[list[FieldGuideEntry]] = [[]]
    used = TITLE_LINES
    for e in entries:
        size = len(_entry(e))
        if parts[-1] and used + size > PAGE_LINES:
            parts.append([])
            used = TITLE_LINES
        parts[-1].append(e)
        used += size
    return parts


def render(guide: FieldGuideSettings, sections: GuideSections) -> str:
    """The index page: the header, the themes (a link to each page, or each part, with its
    field count) and the situations."""
    themes = _themes(guide)
    group_of = _groups(guide, sections)
    lines = [HEADER]
    if themes:
        lines += [f"## Themes ({len(guide.fields)} fields)", ""]
        for theme, entries in themes.items():
            links = [
                theme_path(group_of[theme], theme, n).removeprefix("docs/data/")
                for n, _ in enumerate(_parts(entries), 1)
            ]
            more = "".join(f", [part {n}]({link})" for n, link in enumerate(links[1:], 2))
            names = ", ".join(f"`{e.name}`" for e in entries)
            lines += [f"- [{theme.capitalize()}]({links[0]}){more} ({len(entries)}): {names}"]
        lines.append("")
    if guide.situations:
        lines += ["## Situations that fool several thresholds", ""]
        for s in guide.situations:
            affects = ", ".join(f"`{f}`" for f in s.affects)
            lines += [
                f"### {s.name.capitalize()}",
                "",
                f"**Signs.** {s.signs}",
                "",
                f"**Affects.** {affects}",
                "",
                f"**What to do.** {s.do}",
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def render_theme(theme: str, entries: Iterable[FieldGuideEntry], part: int = 1) -> str:
    """One page of a theme: its fields in file order (``part`` 2 and up say they continue)."""
    title = f"# Field guide: {theme}" + (f" (part {part})" if part > 1 else "")
    lines = [
        title,
        "",
        f"Generated by `make features-doc` from `{SOURCE}`; edit those files, not this page. "
        "How to read the guide, and the situations that fool several thresholds: "
        "[field-guide.md](../../field-guide.md).",
        "",
    ]
    for e in entries:
        lines += _entry(e)
    return "\n".join(lines).rstrip() + "\n"


def pages(guide: FieldGuideSettings, sections: GuideSections) -> dict[str, str]:
    """Every page by repository path: the index, then the parts of each theme."""
    out = {PATH: render(guide, sections)}
    group_of = _groups(guide, sections)
    for theme, entries in _themes(guide).items():
        for n, part in enumerate(_parts(entries), 1):
            out[theme_path(group_of[theme], theme, n)] = render_theme(theme, part, n)
    return out
